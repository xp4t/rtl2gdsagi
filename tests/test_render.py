def test_placement_padding_is_set_before_placement(ctx):
    """Padding reserves space; setting it afterwards reclaims nothing.

    Cells packed edge to edge leave the router no room to land the via pads it
    needs to reach their pins, which surfaces as li1 spacing violations at
    signoff rather than as an honest routing failure.
    """
    ir = IR()
    ir.update("placement", {"padding_sites": 2})
    text = render(StageId.PLACEMENT, ir, ctx)
    assert "set_placement_padding -global -left 2 -right 2" in text
    assert text.index("set_placement_padding") < text.index("global_placement")
