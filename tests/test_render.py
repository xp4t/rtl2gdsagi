def test_hold_is_repaired_with_routed_parasitics_not_just_estimates(ctx):
    """Post-CTS repair alone cannot see the violation.

    With placement estimates OpenROAD reports "No hold violations found" and
    hold reads +0.058 ns; real interconnect turns it to -0.124 ns at signoff.
    The repair has to run where the parasitics are close to final, and before
    a detailed route that can wire in whatever cells it inserts.
    """
    text = render(StageId.ROUTING, IR(), ctx)
    assert "repair_timing -hold" in text
    assert "estimate_parasitics -global_routing" in text
    assert text.index("global_route") < text.index("repair_timing -hold")
    assert text.index("repair_timing -hold") < text.index("detailed_route")


def test_disabling_hold_repair_removes_it_from_routing_too(ctx):
    ir = IR()
