def test_cts_repairs_hold_after_the_clock_tree_exists(ctx):
    """Hold is fixed by adding delay on short paths, and nowhere else.

    It belongs after clock_tree_synthesis because hold is dominated by clock
    skew, which is not a physical thing until the tree exists. Without this
    step the flow has no mechanism to fix hold at all -- it can only report the
    violation and stop.
    """
    text = render(StageId.CTS, IR(), ctx)
    assert "repair_timing -hold" in text
    assert text.index("clock_tree_synthesis") < text.index("repair_timing -hold")
    # Legalise afterwards: the repair inserts cells.
    assert text.index("repair_timing -hold") < text.index("detailed_placement")


