def test_antenna_repair_sits_between_global_and_detailed_route(ctx):
    """Ordering regression.

    `repair_antennas` creates diode wires using live global-routing state.
    Placed after `detailed_route` that state is gone and OpenROAD aborts with
    GRT-0221 ("Cannot create wire for net ..."), after having already spent the
    full detailed-routing runtime.
    """
    text = render(StageId.ROUTING, IR(), ctx)
    g = text.index("global_route")
    r = text.index("repair_antennas")
    d = text.index("detailed_route")
    assert g < r < d, "repair_antennas must run between global and detailed route"


