def test_synthesis_gives_abc_the_real_clock_period(ctx):
    """Yosys does not read SDC.

    The target period reaches synthesis only through abc's -D flag, in
    picoseconds. The old value was a literal `-D 1` — one picosecond — so the
    DELAY strategies were optimising against an impossible target, which abc
    treats as no constraint at all. Synthesis was never timing-driven.
    """
    ir = IR()
    ir.update("synthesis", {"strategy": "DELAY0"})
    ctx.facts["clocks"] = [{"name": "i_clk", "period_ns": 10.0}]
    line = next(l for l in render(StageId.SYNTHESIS, ir, ctx).splitlines()
                if l.startswith("abc "))
    assert "-D 10000" in line          # 10 ns expressed in ps


