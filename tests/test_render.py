"""Renderer tests.

The load-bearing property is byte-identity: the same IR must always produce the
same script. Without it, "diff attempt 3 against attempt 4" is meaningless and
controlled A/B comparison (review 12) cannot work.

The second property is that the renderer is the *only* thing that writes tool
syntax, so these tests also check that generated scripts never contain a
construct that would weaken a check.
"""

from __future__ import annotations

import pytest

from rtl2gdsagi.ir import IR
from rtl2gdsagi.render import RenderContext, render
from rtl2gdsagi.stages import StageId

RENDERABLE = [
    StageId.SDC, StageId.SYNTHESIS, StageId.LEC_SYNTH,
    StageId.STA_PRE, StageId.STA_POSTCTS, StageId.STA_SIGNOFF,
    StageId.FLOORPLAN, StageId.PDN, StageId.PLACEMENT, StageId.CTS,
    StageId.ROUTING, StageId.EXTRACTION, StageId.ANTENNA, StageId.GDSOUT,
]


@pytest.fixture
def ctx(fake_pdk, tmp_path) -> RenderContext:
    work = tmp_path / "work"
    work.mkdir()
    keys = [
        "netlist", "sdc", "floorplan_def", "pdn_def", "placement_def",
        "cts_def", "routed_def", "routed_netlist", "spef", "final_gds",
    ]
    inputs = {}
    for k in keys:
        p = work / f"{k}.dat"
        p.write_text(f"# {k}\n", encoding="utf-8")
        inputs[k] = p
    outputs = {k: work / f"out_{k}" for k in keys + [
        "synth_json", "placed_netlist", "cts_netlist", "congestion_report",
        "route_drc", "antenna_report", "drc_report", "lvs_report",
    ]}
    return RenderContext(
        top="widget", pdk=fake_pdk, work_dir=work,
        inputs=inputs, outputs=outputs,
        facts={
            "sources": [str(work / "widget.v")],
            "clocks": [{"name": "i_clk", "period_ns": 10.0}],
            "inputs": ["i_clk", "i_rst_n", "i_data"],
            "outputs": ["o_data"],
            "cell_gds": [str(fake_pdk.cell_gds()[0])] if fake_pdk.cell_gds() else [],
            "site": "unithd",
        },
    )


@pytest.mark.parametrize("stage", RENDERABLE, ids=lambda s: s.value)
def test_rendering_is_byte_identical(stage, ctx):
    """Same IR in, same bytes out. This is what makes diffs meaningful."""
    ir = IR()
    a = render(stage, ir, ctx)
    b = render(stage, IR(), ctx)
    assert a == b
    assert a.startswith("# generated by rtl2gdsagi")


@pytest.mark.parametrize("stage", RENDERABLE, ids=lambda s: s.value)
def test_rendered_scripts_contain_no_timestamp(stage, ctx):
    """A clock reading in the output would destroy byte-identity."""
    import re
    text = render(stage, IR(), ctx)
    assert not re.search(r"\b(20\d\d-\d\d-\d\d|\d\d:\d\d:\d\d)\b", text)


