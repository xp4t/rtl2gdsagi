def test_detailed_route_is_bounded_to_the_same_layers_as_global_route(ctx):
    """set_routing_layers binds the global router only. Without explicit
    bounds the detailed router uses the whole stack, drops onto li1, and
    lands wires 0.145um from the cells' li1 power rails -- li.3 spacing
    violations that detailed_route itself reports as clean."""
    ir = IR()
    ir.update("routing", {"min_layer": 2, "max_layer": 4})
    text = render(StageId.ROUTING, ir, ctx)
    assert "set_routing_layers -signal met2-met4" in text
    droute = next(l for l in text.splitlines() if l.startswith("detailed_route"))
    assert "-bottom_routing_layer met2" in droute
    assert "-top_routing_layer met4" in droute


def test_signoff_scripts_never_suppress_checks(ctx):
    """No rendered script may contain a waiver construct."""
    banned = ("waive", "skip_rule", "ignore_error", "-force_pass",
              "set_dont_check", "suppress")
    for stage in RENDERABLE:
        text = render(stage, IR(), ctx).lower()
        for token in banned:
            assert token not in text, f"{stage} emitted {token!r}"


